import express from 'express';
import cors from 'cors';

const app = express();
app.use(cors());
app.use(express.json());

app.get('/api/health', (req, res) => {
  res.json({ status: 'ok' });
});

const PORT = 5010;
app.listen(PORT, () => console.log(`Mock API running on http://localhost:${PORT}`));